#!/usr/bin/env python3
"""Generates zdisplay's Wayland protocol tables from the protocol XML files.

    tools/wlgen.py > system/zdisplay/wl_protocol.h

For each interface zdisplay speaks it writes the version it supports, the
opcodes of its requests and events as enums, and each request's argument
signature as a string, the way the wire carries it:

    i int  u uint  f fixed  s string  o object  n new_id  a array  h fd
    ? before a letter: may be null (strings and objects)

A new_id without an interface (wl_registry.bind) is written "sun": the
interface name and version travel on the wire before the id. Requests also
note which interface a new_id creates. The XML comes from the wayland and
wayland-protocols projects (/usr/share/wayland, /usr/share/wayland-protocols).
"""
import sys
import xml.etree.ElementTree as ET

W = "/usr/share/wayland/wayland.xml"
P = "/usr/share/wayland-protocols"

# (xml file, interface, version zdisplay offers)
INTERFACES = [
    (W, "wl_display", 1), (W, "wl_registry", 1), (W, "wl_callback", 1),
    (W, "wl_compositor", 6), (W, "wl_surface", 6), (W, "wl_region", 1),
    (W, "wl_shm", 1), (W, "wl_shm_pool", 1), (W, "wl_buffer", 1),
    (W, "wl_seat", 8), (W, "wl_pointer", 8), (W, "wl_keyboard", 8), (W, "wl_touch", 8),
    (W, "wl_output", 4),
    (W, "wl_data_device_manager", 3), (W, "wl_data_device", 3), (W, "wl_data_source", 3), (W, "wl_data_offer", 3),
    (W, "wl_subcompositor", 1), (W, "wl_subsurface", 1),
    (P + "/stable/xdg-shell/xdg-shell.xml", "xdg_wm_base", 5),
    (P + "/stable/xdg-shell/xdg-shell.xml", "xdg_positioner", 5),
    (P + "/stable/xdg-shell/xdg-shell.xml", "xdg_surface", 5),
    (P + "/stable/xdg-shell/xdg-shell.xml", "xdg_toplevel", 5),
    (P + "/stable/xdg-shell/xdg-shell.xml", "xdg_popup", 5),
    (P + "/stable/viewporter/viewporter.xml", "wp_viewporter", 1),
    (P + "/stable/viewporter/viewporter.xml", "wp_viewport", 1),
    (P + "/unstable/relative-pointer/relative-pointer-unstable-v1.xml", "zwp_relative_pointer_manager_v1", 1),
    (P + "/unstable/relative-pointer/relative-pointer-unstable-v1.xml", "zwp_relative_pointer_v1", 1),
    (P + "/unstable/pointer-constraints/pointer-constraints-unstable-v1.xml", "zwp_pointer_constraints_v1", 1),
    (P + "/unstable/pointer-constraints/pointer-constraints-unstable-v1.xml", "zwp_locked_pointer_v1", 1),
    (P + "/unstable/pointer-constraints/pointer-constraints-unstable-v1.xml", "zwp_confined_pointer_v1", 1),
    (P + "/unstable/xdg-decoration/xdg-decoration-unstable-v1.xml", "zxdg_decoration_manager_v1", 1),
    (P + "/unstable/xdg-decoration/xdg-decoration-unstable-v1.xml", "zxdg_toplevel_decoration_v1", 1),
    (P + "/unstable/xdg-output/xdg-output-unstable-v1.xml", "zxdg_output_manager_v1", 3),
    (P + "/unstable/xdg-output/xdg-output-unstable-v1.xml", "zxdg_output_v1", 3),
    (P + "/stable/linux-dmabuf/linux-dmabuf-v1.xml", "zwp_linux_dmabuf_v1", 4),
    (P + "/stable/linux-dmabuf/linux-dmabuf-v1.xml", "zwp_linux_buffer_params_v1", 4),
    (P + "/stable/linux-dmabuf/linux-dmabuf-v1.xml", "zwp_linux_dmabuf_feedback_v1", 4),
]

CODES = {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o", "new_id": "n", "array": "a", "fd": "h"}


def sig(msg):
    out, made = "", ""
    for a in msg.findall("arg"):
        t = a.get("type")
        if t == "new_id" and not a.get("interface"):
            out += "sun"
            continue
        if a.get("allow-null") == "true":
            out += "?"
        out += CODES[t]
        if t == "new_id":
            made = a.get("interface")
    return out, made


def main():
    trees = {}
    print("/* Generated by tools/wlgen.py from the Wayland protocol XML. Do not edit. */")
    print("#pragma once\n")
    names = []
    for path, name, version in INTERFACES:
        root = trees.setdefault(path, ET.parse(path).getroot())
        iface = next(i for i in root.findall("interface") if i.get("name") == name)
        names.append(name)
        up = name.upper()
        reqs = iface.findall("request")  # every message: an opcode is its place in the XML
        evs = iface.findall("event")
        print(f"/* {name}, version {version} */")
        print(f"#define {up}_VERSION {version}")
        if reqs:
            print("enum { " + ", ".join(f"{up}_{r.get('name').upper()}" for r in reqs) + " };")
        if evs:
            print("enum { " + ", ".join(f"{up}_EV_{e.get('name').upper()}" for e in evs) + " };")
        print(f"static const WlMessage {name}_requests[] = {{")
        for r in reqs:
            s, made = sig(r)
            made = f'"{made}"' if made else "NULL"
            print(f'\t{{ "{r.get("name")}", "{s}", {made}, {int(r.get("since", "1"))} }},')
        if not reqs:
            print('\t{ NULL, NULL, NULL, 0 },')
        print("};")
        print(f"static const WlInterface {name}_interface = {{ \"{name}\", {version}, {name}_requests, {len(reqs)}, {len(evs)} }};\n")
    print("static const WlInterface *const WL_INTERFACES[] = {")
    for n in names:
        print(f"\t&{n}_interface,")
    print("};")


if __name__ == "__main__":
    main()
