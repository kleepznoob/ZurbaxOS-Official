#!/bin/sh
# Regenerates libzr/include/zr/syscalls.h from the kernel's x86-64 syscall table.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
TBL=${1:-$ROOT/build/linux-6.18.55/arch/x86/entry/syscalls/syscall_64.tbl}
{
	echo "/* Generated by tools/gen-syscalls.sh from the Linux x86-64 syscall table. */"
	echo "#pragma once"
	awk '$1 ~ /^[0-9]+$/ && ($2 == "common" || $2 == "64") { printf "#define SYS_%s %s\n", $3, $1 }' "$TBL"
} >"$ROOT/libzr/include/zr/syscalls.h"
